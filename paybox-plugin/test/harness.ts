// Drives the plugin exactly as PayBox does: newline-delimited MCP 2026-07-28 requests through
// serveStdio, one fresh server per call. The only differences are the transport (in-process
// streams) and an injected fetch, so no test reaches the network (test/fake-mcp.test.ts reaches a
// server on 127.0.0.1 that the test itself started, and nothing else).
import { PassThrough } from "node:stream";
import { createInterface } from "node:readline";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { serveStdio, StdioServerTransport } from "@modelcontextprotocol/server/stdio";

import { lineSafe } from "../src/line-safe.ts";
import { createServer, type Deps } from "../src/server.ts";

// Nothing in the suite may use the real fetch.
export const REAL_FETCH = globalThis.fetch;
globalThis.fetch = (() => {
  throw new Error("network access in a test");
}) as typeof fetch;

export const ROOT = fileURLToPath(new URL("..", import.meta.url));

/** The facilitator's whole tools/list, as POST /mcp answers it (generated by src/mcp.rs). */
export function facilitatorTools(): Record<string, any>[] {
  return JSON.parse(readFileSync(`${ROOT}test/fixtures/facilitator-tools.json`, "utf8")).tools;
}

export interface Recorded {
  url: string;
  method: string;
  redirect: RequestRedirect | undefined;
  headers: Record<string, string>;
  body: string | undefined;
  signal: AbortSignal | null | undefined;
}

/** A fetch that answers each call with the next of `answers` (a Response, or an error to throw). */
export function fakeFetch(...answers: (Response | Error)[]) {
  const calls: Recorded[] = [];
  const fetchImpl = async (input: string, init: RequestInit) => {
    const headers: Record<string, string> = {};
    new Headers(init.headers).forEach((value, key) => {
      headers[key] = value;
    });
    calls.push({
      url: input,
      method: init.method ?? "GET",
      redirect: init.redirect,
      headers,
      body: typeof init.body === "string" ? init.body : undefined,
      signal: init.signal,
    });
    const next = answers.shift();
    if (!next) throw new Error("unexpected extra request");
    if (next instanceof Error) throw next;
    return next;
  };
  return { fetchImpl, calls };
}

export function json(status: number, body: unknown): Response {
  return new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
}

/** The facilitator's JSON-RPC answer with this result. */
export function facilitatorResult(result: unknown): Response {
  return json(200, { jsonrpc: "2.0", id: 1, result });
}

export function deps(fetchImpl: Deps["fetch"]): Deps {
  return { fetch: fetchImpl };
}

export async function rpc(d: Deps, method: string, params: Record<string, unknown> = {}): Promise<any> {
  return JSON.parse(await rpcLine(d, method, params));
}

/** The response line exactly as the plugin writes it on stdout, newline aside. */
export async function rpcLine(d: Deps, method: string, params: Record<string, unknown> = {}): Promise<string> {
  const input = new PassThrough();
  const output = new PassThrough();
  const handle = serveStdio(() => createServer(d), {
    legacy: "reject",
    // As src/plugin.ts wires it.
    transport: new StdioServerTransport(input, lineSafe(output)),
  });
  const lines = createInterface({ input: output, crlfDelay: Infinity });
  try {
    input.write(
      `${JSON.stringify({
        jsonrpc: "2.0",
        id: 2,
        method,
        params: {
          ...params,
          _meta: {
            "io.modelcontextprotocol/protocolVersion": "2026-07-28",
            "io.modelcontextprotocol/clientInfo": { name: "facilitator-plugin-tests", version: "0" },
            "io.modelcontextprotocol/clientCapabilities": {},
          },
        },
      })}\n`,
    );
    for await (const line of lines) {
      const message = JSON.parse(line);
      if (message.id === 2) return line;
    }
    throw new Error("no response");
  } finally {
    lines.close();
    await handle.close();
  }
}

export async function callTool(d: Deps, name: string, args: Record<string, unknown> = {}): Promise<any> {
  const response = await rpc(d, "tools/call", { name, arguments: args });
  if (response.error) throw new Error(`JSON-RPC error: ${JSON.stringify(response.error)}`);
  return response.result;
}

export function text(result: any): string {
  return result.content.map((block: { text: string }) => block.text).join("\n");
}
